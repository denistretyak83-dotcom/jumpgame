"""BaseCharacter -- abstract contract for all moving entities.

Полиморфизм: Game обращается к ЛЮБОЙ сущности единообразно
через update(), get_render_info(), spawn_copy() — не зная её реального типа.
"""
from abc import ABC, abstractmethod
import pygame


class BaseCharacter(ABC):
    """Лёгкий контракт движущейся сущности (игрок, враги)."""

    def __init__(self, rect, animations=None):
        self.rect = rect
        # Безопасный словарь анимаций (пустой, если анимаций нет)
        self.animations = animations if animations else {}
        self.is_dead = False

    # ------------------------------------------------------------------
    # Контракт, который обязан реализовать каждый наследуемый класс
    # ------------------------------------------------------------------

    @abstractmethod
    def update(self, dt: float, ctx) -> None:
        """Единый метод обновления. Вызывается из Game в общем цикле.

        ctx — контекст (ключи ввода, платформы, сцена и т.д.).
        Каждая сущность берёт из ctx только то, что ей нужно,
        либо игнорирует его вовсе.
        """
        ...

    @abstractmethod
    def get_render_info(self) -> dict:
        """Отдаёт данные для отрисовки. Renderer рисует по ним, не зная тип.

        Ожидается как минимум:
            {
                'frame': Surface | None,   # текущий кадр анимации
                'rect': pygame.Rect,        # позиция на экране
                'facing_left': bool,        # отзеркаливание
                'is_dead': bool,            # состояние (для особой отрисовки)
            }
        """
        ...

    # ------------------------------------------------------------------
    # Общий механизм, который можно переопределить
    # ------------------------------------------------------------------

    def spawn_copy(self):
        """Возвращает возрождённую копию сущности.

        По умолчанию возвращает саму себя. Классы, которые нужно
        возрождать из стартового состояния (враги), переопределяют.
        """
        return self

    # ------------------------------------------------------------------
    # Удобные хелперы (доступ к кадру анимации)
    # ------------------------------------------------------------------

    def _current_frame(self, anim_key: str):
        """Фрейм из конкретной анимации (с защитой от отсутствия)."""
        anim = self.animations.get(anim_key)
        if anim is None:
            return None
        return anim.current()